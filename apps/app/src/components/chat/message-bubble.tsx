import { memo } from "react";
import type { ChatMessage, Expert } from "../../lib/chat-api";
import { ChatMarkdown } from "./chat-markdown";
import { ExpertAvatar } from "./expert-avatar";
import { formatMessageTime } from "./chat-utils";

function resolveMediaUrl(url: string): string {
  return url.startsWith("http") ? url : `${window.location.origin}${url}`;
}

interface MessageMediaProps {
  message: ChatMessage;
  expertName?: string;
}

export const MessageMedia = memo(function MessageMedia({ message, expertName }: MessageMediaProps) {
  if (!message.mediaUrl || !message.mediaType) return null;

  if (message.mediaType === "video") {
    return (
      <video
        controls
        src={resolveMediaUrl(message.mediaUrl)}
        aria-label={`Video generated by ${expertName ?? "the expert"}`}
        className="mt-3 max-h-80 w-full rounded-xl border border-app-rule bg-black"
      >
        <track kind="captions" srcLang="en" label="English captions" />
      </video>
    );
  }

  return (
    <img
      src={resolveMediaUrl(message.mediaUrl)}
      alt={`Visual generated by ${expertName ?? "the expert"}`}
      loading="lazy"
      decoding="async"
      className="mt-3 max-h-80 max-w-full rounded-xl border border-app-rule object-contain"
    />
  );
});

export const UserMessage = memo(function UserMessage({ message }: { message: ChatMessage }) {
  return (
    <div className="flex justify-end pl-8 sm:pl-16">
      <div className="flex max-w-[88%] flex-col items-end gap-1.5">
        <div className="rounded-3xl rounded-br-lg bg-ink px-4 py-3 text-[15px] leading-relaxed text-white shadow-lift">
          <p className="break-words whitespace-pre-wrap [overflow-wrap:anywhere]">
            {message.content}
          </p>
        </div>
        <time
          dateTime={message.createdAt}
          className="pr-1 text-[11px] tabular-nums text-muted-foreground"
        >
          {formatMessageTime(message.createdAt)}
        </time>
      </div>
    </div>
  );
});

interface AssistantMessageGroupProps {
  expert: Expert | null;
  messages: ChatMessage[];
}

export const AssistantMessageGroup = memo(function AssistantMessageGroup({
  expert,
  messages,
}: AssistantMessageGroupProps) {
  return (
    <div className="chat-group flex gap-3 sm:gap-4">
      <ExpertAvatar expert={expert} size="md" className="mt-0.5" />
      <div className="min-w-0 flex-1">
        <div className="flex flex-wrap items-baseline gap-x-2 gap-y-0.5">
          <span className="font-display text-sm font-semibold text-ink">
            {expert?.name ?? "Expert"}
          </span>
          {expert?.role && <span className="text-xs text-muted-foreground">{expert.role}</span>}
        </div>

        <div className="mt-2 rounded-2xl rounded-tl-sm border border-app-rule/70 bg-card/80 px-4 py-3.5 shadow-xs">
          {messages.map((message, index) => (
            <article
              key={message.id}
              className={
                index > 0 ? "mt-4 border-t border-dashed border-app-rule/70 pt-4" : undefined
              }
            >
              <ChatMarkdown>{message.content}</ChatMarkdown>
              <MessageMedia message={message} expertName={expert?.name} />
              <time
                dateTime={message.createdAt}
                className="mt-2 block text-[11px] tabular-nums text-muted-foreground"
              >
                {formatMessageTime(message.createdAt)}
              </time>
            </article>
          ))}
        </div>
      </div>
    </div>
  );
});
